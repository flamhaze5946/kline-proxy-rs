#!/usr/bin/env python3
"""F=16 concurrent evidence clients against kp-1m at minute boundaries (P4 request shapes).

Each minute T, client i (0..F-1) sends one with_evidence bulk at T + offset_i, where offsets are
spread over [--offset-min, --offset-max] s. Clients alternate between the two P4 shapes:
  explicit  POST with an explicit symbol list (--symbols-file, ~523 coins; default: the first
            --explicit-n trading coins reported by kp-1m), limit --limit;
  market    POST without `symbols` (full market), limit --limit.
Per request it records send time, latency, HTTP status, Binance-style error code, response bytes,
per-coin acceptance of the latest minute (final/absent) and invariant violations. Summary per
shape: count, error codes, latency p50/p90/p99/max, acceptance min/p50. Local or VPS loopback
only (kp-1m answers from memory; no Binance traffic is generated by this tool).
"""
import argparse
import json
import os
import statistics
import sys
import threading
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kp_lib as L  # noqa: E402


def pct(xs, q):
    if not xs:
        return None
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(round(q * (len(xs) - 1))))]


def one(base, shape, syms, limit, T, offset, out):
    L.sleep_until_ms(int((T + offset) * 1000))
    rec = {"T": T * 1000, "offset": offset, "shape": shape, "t_send_ms": L.now_ms()}
    try:
        s, d, raw, _, el = L.evidence_post(base, limit, syms if shape == "explicit" else None, timeout=30)
        rec.update(status=s, latency_ms=round(el * 1000, 1), bytes=len(raw))
        if s == 200:
            m = d["window"]["last_open"]
            trading = [k for k, v in d["status"].items() if v["state"] == "trading"]
            acc = sum(1 for k in trading if L.minute_state(d, k, m) in ("final", "absent"))
            rec.update(accepted=acc, trading=len(trading),
                       invariant=L.window_violations(d, requested=sorted(set(syms)) if shape == "explicit" else None,
                                                     limit=limit)[:3])
        else:
            rec["code"] = (d or {}).get("code")
    except Exception as e:
        rec.update(status=None, error=repr(e))
    out.append(rec)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--base", default="http://127.0.0.1:1891")
    ap.add_argument("--clients", type=int, default=16)
    ap.add_argument("--minutes", type=int, default=5)
    ap.add_argument("--limit", type=int, default=100)
    ap.add_argument("--symbols-file", default=None)
    ap.add_argument("--explicit-n", type=int, default=523)
    ap.add_argument("--offset-min", type=float, default=1.0)
    ap.add_argument("--offset-max", type=float, default=2.0)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    assert a.base.startswith("http://127.0.0.1:"), "load test targets the loopback kp-1m only"
    if a.symbols_file:
        with open(a.symbols_file) as f:
            syms = [x.strip() for x in f if x.strip()]
    else:
        s, d = L.http_json(L.evidence_url(a.base, 1))[:2]
        syms = sorted(k for k, v in d["status"].items() if v["state"] == "trading")[: a.explicit_n]
    recs = []
    span = a.offset_max - a.offset_min
    for k in range(a.minutes):
        T = (int(time.time()) // 60 + 1) * 60
        ths = []
        for i in range(a.clients):
            shape = "explicit" if i % 2 == 0 else "market"
            off = a.offset_min + span * i / max(1, a.clients - 1)
            ths.append(threading.Thread(target=one, args=(a.base, shape, syms, a.limit, T, off, recs), daemon=True))
        for t in ths:
            t.start()
        for t in ths:
            t.join(60)
        print("minute %s: %d requests" % (L.iso(T * 1000), len(ths)), flush=True)
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w") as f:
        for r in recs:
            f.write(json.dumps(r) + "\n")
    summary = {}
    for shape in ("explicit", "market"):
        rs = [r for r in recs if r["shape"] == shape]
        lat = [r["latency_ms"] for r in rs if r.get("status") == 200]
        accr = [r["accepted"] / r["trading"] for r in rs if r.get("trading")]
        codes = {}
        for r in rs:
            key = str(r.get("status")) + ("/" + str(r["code"]) if r.get("code") is not None else "")
            codes[key] = codes.get(key, 0) + 1
        summary[shape] = {"n": len(rs), "status": codes, "n_symbols": len(syms) if shape == "explicit" else "market",
                          "latency_ms": {"p50": pct(lat, .5), "p90": pct(lat, .9), "p99": pct(lat, .99),
                                         "max": max(lat) if lat else None},
                          "accept_latest": {"min": min(accr) if accr else None,
                                            "p50": statistics.median(accr) if accr else None},
                          "invariant_violations": sum(1 for r in rs if r.get("invariant"))}
    print(json.dumps(summary, indent=1))
    with open(a.out + ".summary.json", "w") as f:
        json.dump(summary, f, indent=1)


if __name__ == "__main__":
    main()
